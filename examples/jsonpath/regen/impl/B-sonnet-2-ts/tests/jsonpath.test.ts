test('R13 filter syntax', () => {
  const d = '[{"a":1,"b":2},{"a":2},{"b":3}]';
  const v01 = '[{"a":1,"b":2},{"a":2}]';
  ok('$[?@.a]', d, v01, ['$[0]', '$[1]']);
  ok('$[? @.a ]', d, v01, ['$[0]', '$[1]']);
  ok('$[?((@.a))]', d, v01, ['$[0]', '$[1]']);
  ok('$[?@.a==1]', d, '[{"a":1,"b":2}]', ['$[0]']);
  ok('$[?1 == @.a]', d, '[{"a":1,"b":2}]', ['$[0]']);
  ok('$[?! @.a]', d, '[{"b":3}]', ['$[2]']);
  ok('$[?!(@.a == 1)]', d, '[{"a":2},{"b":3}]', ['$[1]', '$[2]']);
  ok('$[?!(!@.a)]', d, v01, ['$[0]', '$[1]']);
  ok('$[?@.a&&@.b]', d, '[{"a":1,"b":2}]', ['$[0]']);
  ok('$[?@.a == 2 || @.b == 3]', d, '[{"a":2},{"b":3}]', ['$[1]', '$[2]']);
  ok('$[?@.a\n==\n1]', d, '[{"a":1,"b":2}]', ['$[0]']);
  ok('$[?@.a].b', d, '[2]', ["$[0]['b']"]);
  for (const q of ['$[?]', '$[@.a]', '$[?@.a ==]', '$[?== 1]', '$[?@.a = 1]', '$[?@.a === 1]', '$[?@.a <> 1]',
    '$[?@.a =< 1]', '$[?@.a = = 1]', '$[?@.a == 1 == 1]', '$[?!!@.a]', '$[?!@.a == 1]', '$[?(@.a) == 1]',
    '$[?@.a & @.b]', '$[?@.a | @.b]', '$[?@.a and @.b]', '$[?(@.a]', '$[?@.a)]', '$[?()]', '$[?true]',
    '$[?false]', '$[?null]', '$[?1]', "$[?'a']", '$[?@ == [1]]', '$[?@ == {}]', '$[?@.a + 1 == 2]', '$[?@.a == True]']) bad(q);
});

test('R14 filter semantics', () => {
  const d = '{"a":[3,5,1,2,4,6,{"b":"j"},{"b":"k"},{"b":{}},{"b":"kilo"}],"o":{"p":1,"q":2,"r":3,"s":5,"t":{"u":6}},"e":"f"}';
  ok("$.a[?@.b == 'kilo']", d, '[{"b":"kilo"}]', ["$['a'][9]"]);
  ok('$.a[?@>3.5]', d, '[5,4,6]', ["$['a'][1]", "$['a'][4]", "$['a'][5]"]);
  ok('$.o[?@<3, ?@<3]', d, '[1,2,1,2]', ["$['o']['p']", "$['o']['q']", "$['o']['p']", "$['o']['q']"]);
  ok('$.a[?@<2 || @.b == "k"]', d, '[1,{"b":"k"}]', ["$['a'][2]", "$['a'][7]"]);
  ok('$.o[?@>1 && @<4]', d, '[2,3]', ["$['o']['q']", "$['o']['r']"]);
  ok('$.a[?@.b == $.x]', d, '[3,5,1,2,4,6]', [0, 1, 2, 3, 4, 5].map((i) => `$['a'][${i}]`));
  none('$[?@ == 1]', '1');
  ok('$[?@ > 1]', '{"x":1,"y":2,"z":3}', '[2,3]', ["$['y']", "$['z']"]);
  ok('$.a[?@ == $.n]', '{"a":[1,2,3],"n":2}', '[2]', ["$['a'][1]"]);
  ok('$[?$.flag]', '{"flag":false,"v":1}', '[false,1]', ["$['flag']", "$['v']"]);
  ok('$[?@[?@ > 2]]', '[[1,2],[3]]', '[[3]]', ['$[1]']);
  none('$[?@.a < @.b]', '[{"a":"x","b":1},{"a":[1],"b":[2]}]');
});

