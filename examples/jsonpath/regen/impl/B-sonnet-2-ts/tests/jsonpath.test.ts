const R6 = '{"o":{"j":1,"k":2},"a":[5,3,[{"j":4},{"k":6}]]}';
test('R6 descendant segments', () => {
  ok('$..j', R6, '[1,4]', ["$['o']['j']", "$['a'][2][0]['j']"]);
  ok('$..[0]', R6, '[5,{"j":4}]', ["$['a'][0]", "$['a'][2][0]"]);
  const all = run('$..*', R6).result;
  assert.strictEqual(all.values.length, 11);
  assert.deepStrictEqual(run('$..[*]', R6).result, all);
  assert.deepStrictEqual(all.paths.slice(0, 4), ["$['o']", "$['a']", "$['o']['j']", "$['o']['k']"]);
  ok('$.o..[*, *]', R6, '[1,2,1,2]', ["$['o']['j']", "$['o']['k']", "$['o']['j']", "$['o']['k']"]);
  ok("$..['j','k']", R6, '[1,2,4,6]', ["$['o']['j']", "$['o']['k']", "$['a'][2][0]['j']", "$['a'][2][1]['k']"]);
  ok('$..a', '{"a":{"a":1}}', '[{"a":1},1]', ["$['a']", "$['a']['a']"]);
  ok('$..[?@ > 1]', '{"x":[1,2,{"y":3}],"z":5}', '[5,2,3]', ["$['z']", "$['x'][1]", "$['x'][2]['y']"]);
  none('$..*', '5');
  ok('$..[1]', '[[0,1],2]', '[2,1]', ['$[1]', '$[0][1]']);
  for (const q of ['$..', '$...a', '$..1']) bad(q);
});

