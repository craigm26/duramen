import test from 'node:test';
import assert from 'node:assert';
import { handleLine } from '../src/protocol.ts';

function run(query: string, doc: string): any {
  const line = `{"id":"t","op":"query","input":{"query":${JSON.stringify(query)},"document":${doc}}}`;
  return JSON.parse(handleLine(line));
}

function ok(query: string, doc: string, values: string, paths: string[]): void {
  const r = run(query, doc);
  assert.deepStrictEqual(r.result, { values: JSON.parse(values), paths }, query);
}

function bad(query: string): void {
  assert.deepStrictEqual(run(query, 'null'), { id: 't', error: 'invalid_query' }, JSON.stringify(query));
}

const none = (q: string, d: string) => ok(q, d, '[]', []);

test('R1 request handling', () => {
  assert.strictEqual(
    handleLine('{"id":"r1","op":"query","input":{"query":"$.a","document":{"a":1}}}'),
    '{"id":"r1","result":{"values":[1],"paths":["$[\'a\']"]}}',
  );
  assert.strictEqual(handleLine('{"id":"r3","op":"query","input":{"query":"$"}}'), '{"id":"r3","error":"bad_request"}');
  assert.strictEqual(handleLine('{"id":"r4","op":"evaluate","input":{}}'), '{"id":"r4","error":"unknown_op"}');
  assert.strictEqual(handleLine('{"id":"r5"}'), '{"id":"r5","error":"unknown_op"}');
  assert.strictEqual(handleLine('hello'), '{"id":null,"error":"bad_request"}');
  assert.strictEqual(handleLine('[1,2]'), '{"id":null,"error":"bad_request"}');
  assert.strictEqual(handleLine('{"id":7,"op":"query"}'), '{"id":null,"error":"bad_request"}');
  assert.strictEqual(handleLine('{"id":"r8","op":"query","input":{"query":42,"document":1}}'), '{"id":"r8","error":"bad_request"}');
  assert.strictEqual(handleLine('{"id":"r9","op":"query","input":"$"}'), '{"id":"r9","error":"bad_request"}');
  assert.strictEqual(handleLine('{"id":"r10","op":"query","input":{"query":"$[","document":{}}}'), '{"id":"r10","error":"invalid_query"}');
  assert.strictEqual(
    handleLine('{"id":"r11","op":"query","input":{"query":"$.a","document":1,"extra":true},"x":0}'),
    '{"id":"r11","result":{"values":[],"paths":[]}}',
  );
  assert.strictEqual(handleLine('{"id":"r2","op":"query","input":{"query":"$","document":null}}'), '{"id":"r2","result":{"values":[null],"paths":["$"]}}');
  assert.strictEqual(handleLine('\f'), '{"id":null,"error":"bad_request"}');
  none('$.a.b.c', '[1,2]');
});

