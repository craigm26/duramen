test('R11 slices', () => {
  const d = '["a","b","c","d","e","f","g"]';
  ok('$[1:3]', d, '["b","c"]', ['$[1]', '$[2]']);
  ok('$[1:5:2]', d, '["b","d"]', ['$[1]', '$[3]']);
  ok('$[5:1:-2]', d, '["f","d"]', ['$[5]', '$[3]']);
  ok('$[::-1]', d, '["g","f","e","d","c","b","a"]', ['$[6]', '$[5]', '$[4]', '$[3]', '$[2]', '$[1]', '$[0]']);
  assert.deepStrictEqual(run('$[::]', d).result, run('$[:]', d).result);
  ok('$[1:2:]', d, '["b"]', ['$[1]']);
  ok('$[-2:]', d, '["f","g"]', ['$[5]', '$[6]']);
  ok('$[:2:-1]', d, '["g","f","e","d"]', ['$[6]', '$[5]', '$[4]', '$[3]']);
  ok('$[2:-10:-1]', d, '["c","b","a"]', ['$[2]', '$[1]', '$[0]']);
  ok('$[-10:2]', d, '["a","b"]', ['$[0]', '$[1]']);
  for (const q of ['$[0:0]', '$[3:1]', '$[::0]', '$[10:20]']) none(q, d);
  ok('$[1 : 2 : 1]', d, '["b"]', ['$[1]']);
  ok('$[::9007199254740991]', d, '["a"]', ['$[0]']);
  ok('$[::-9007199254740991]', d, '["g"]', ['$[6]']);
  assert.strictEqual(run('$[-9007199254740991:9007199254740991]', d).result.values.length, 7);
  none('$[1:3]', '{"a":1}');
  none('$[1:3]', '"abcdef"');
  for (const q of ['$[1:2:3:4]', '$[:-0]', '$[01:2]', '$[1:2:0.5]']) bad(q);
});

