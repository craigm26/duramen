test('R18 comparison', () => {
  const d = '{"obj":{"x":"y"},"arr":[2,3]}';
  const all = (c: string) => ok(`$[?${c}]`, d, '[{"x":"y"},[2,3]]', ["$['obj']", "$['arr']"]);
  const nil = (c: string) => none(`$[?${c}]`, d);
  for (const c of ['$.absent1 == $.absent2', '$.absent1 <= $.absent2', '$.absent != \'g\'', '1 <= 2', "'a' <= 'b'",
    '$.obj != $.arr', '$.obj == $.obj', '$.arr == $.arr', '$.obj != 17', '$.obj <= $.obj', '$.arr <= $.arr',
    'true <= true', 'null >= null', "'ab' < 'abc'", "'' < 'a'", "'B' < 'a'", '$.arr[0] == 2', '$.arr[0] == 2.0']) all(c);
  for (const c of ["$.absent == 'g'", '$.absent1 != $.absent2', '1 > 2', "13 == '13'", "'a' > 'b'", '$.obj == $.arr',
    '$.obj != $.obj', '$.arr != $.arr', '$.obj == 17', '$.obj <= $.arr', '$.obj < $.arr', '1 <= $.arr', '1 >= $.arr',
    '1 > $.arr', '1 < $.arr', 'true > true', 'null < null', 'false < true', "'b' < 'abc'"]) nil(c);
  ok("$[?@ < 'b']", '["a","b","c","",1,"B"]', '["a","","B"]', ['$[0]', '$[3]', '$[5]']);
  ok("$[?@ > '\\uE000']", '["😀","a","\\uE000"]', '["😀"]', ['$[0]']);
  ok('$[?@ <= true]', '[false,true]', '[true]', ['$[1]']);
  ok('$[?@.x == @.y]', '[{"x":[1,{"a":2}],"y":[1,{"a":2}]},{"x":{"a":1,"b":2},"y":{"b":2,"a":1}},{"x":[1,2],"y":[2,1]},{"x":{"a":1},"y":{"a":1,"b":2}},{"x":1,"y":1.0},{"x":"1","y":1}]',
    '[{"x":[1,{"a":2}],"y":[1,{"a":2}]},{"x":{"a":1,"b":2},"y":{"b":2,"a":1}},{"x":1,"y":1.0}]', ['$[0]', '$[1]', '$[4]']);
  ok('$[?@.x != 1]', '[{},{"x":1},{"x":2}]', '[{},{"x":2}]', ['$[0]', '$[2]']);
  ok('$[?@.x >= @.x]', '[{"x":{}},{"x":[]},{},{"x":null}]', '[{"x":{}},{"x":[]},{},{"x":null}]', ['$[0]', '$[1]', '$[2]', '$[3]']);
});

